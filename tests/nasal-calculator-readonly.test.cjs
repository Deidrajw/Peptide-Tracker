const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const src=fs.readFileSync("assets/js/10-nexus.js","utf8");
const start=src.indexOf("function nxNasalCalcValidate(v){");
const end=src.indexOf("function nxCalcModeTabs(active){",start);
assert.ok(start>=0&&end>start,"Find actual nasal calculator implementation");
const scope={Number,String,Math,Object};
vm.runInNewContext(src.slice(start,end)+"\nthis.calculate=nxNasalCalcValidate;",scope);
const actual=v=>JSON.parse(JSON.stringify(scope.calculate(v)));
const sample={mass:"5",unit:"mg",finalMl:"5",pumpMl:"0.1"};
const result=actual(sample);
assert.equal(result.error,null);
assert.equal(result.mgPerMl,1);
assert.ok(Math.abs(result.mcgPerActuation-100)<1e-9);
assert.equal(result.theoreticalActuations,50);
assert.deepEqual(actual({...sample,mass:"5000",unit:"mcg"}),result,"mg↔mcg conversion must be exact");
assert.equal(actual({...sample,unit:"iu"}).mcgPerActuation,null);
assert.match(actual({...sample,unit:"iu"}).error,/IU/);
assert.match(actual({...sample,finalMl:"0"}).error,/positive finite/);
assert.match(actual({...sample,pumpMl:"-0.1"}).error,/positive finite/);
assert.match(actual({...sample,pumpMl:"Infinity"}).error,/positive finite/);
assert.match(actual({...sample,pumpMl:"6"}).error,/exceeds/);
assert.equal(actual({...sample,mass:""}).mcgPerActuation,null);
assert.match(actual({...sample,pumpMl:"1e-25"}).error,/safe numeric range/);
assert.match(src,/let nxNasalDraft=\{mass:"",unit:"mg",finalMl:"",pumpMl:""\}/);
assert.ok(!src.slice(start,src.indexOf("function reconCalcView()",end)).includes("localStorage"),"Nasal UI must be storage independent");
assert.ok(!src.slice(start,src.indexOf("function reconCalcView()",end)).includes("nexusCommit"),"Nasal UI must not commit");
assert.ok(!src.slice(start,src.indexOf("function reconCalcView()",end)).includes("state._nasalCalc"),"Nasal inputs must not be part of persistable app state");
console.log("PASS: independent read-only nasal theory mass conversion, pump count, fail-closed validation and no persistence");
