const assert=require('node:assert/strict');
const stock=require('../assets/js/nexus-formulation-stock.js');
const fixture=()=>({supplies:[{id:'vial-existing',name:'Fictional Slew',vials:[{id:'original-vial',remainingMg:10}]}],peptides:{'Fictional Slew':{doses:[{id:'historical',dose:'2',site:'Abdomen — lower L'}]}}});
const oral={id:'capsules-a',compound:'Fictional Slew',containerType:'capsule-bottle',method:'Oral',count:30,mgPerCapsule:5};
const nasal={id:'nasal-a',compound:'Fictional Slew',containerType:'nasal-bottle',method:'Nasal',volumeMl:7,quantityMg:10};
let initial=fixture(),a=stock.add(initial,oral),both=stock.add(a.next,nasal);
assert.deepEqual(initial,fixture(),'original untouched');
assert.deepEqual(both.next.supplies,initial.supplies,'legacy vials unaffected');
assert.deepEqual(both.next.peptides,initial.peptides,'historical dose untouched');
assert.equal(both.next.formulationStocks[0].remainingCount,30);
assert.equal(both.next.formulationStocks[1].remainingMl,7);
assert.equal(both.next.formulationStocks[1].mgPerSpray,null,'no guessed spray strength');
assert.throws(()=>stock.add(both.next,oral),/Duplicate/);
assert.throws(()=>stock.add(initial,{...oral,method:'SubQ'}),/mismatch/);
assert.throws(()=>stock.add(initial,{...oral,count:2.5}),/count/);
assert.throws(()=>stock.add(initial,{...oral,mgPerCapsule:0}),/mg per capsule/);
assert.throws(()=>stock.add(initial,{...nasal,volumeMl:-1}),/volume/);
assert.throws(()=>stock.add(initial,{...nasal,quantityMg:NaN}),/quantity/);
assert.throws(()=>stock.add(initial,{...oral,containerType:'vial'}),/Unsupported/);
let saved=JSON.stringify(initial),writes=0;
const adapter={read:()=>saved,write:v=>{saved=v;writes++}};
const c=stock.commitAdd(initial,oral,adapter);
assert.equal(writes,1);
assert.equal(c.next.formulationStocks.length,1);
assert.equal(JSON.parse(saved).formulationStocks[0].remainingCount,30);
assert.deepEqual(initial,fixture(),'memory remains old until explicit successful swap');
assert.throws(()=>stock.commitAdd(initial,nasal,adapter),/changed/);
assert.equal(writes,1,'stale writes blocked');
let before=JSON.stringify(initial);
assert.throws(()=>stock.commitAdd(initial,nasal,{read:()=>before,write:()=>{throw Error('Quota exceeded')}}),/Quota/);
assert.equal(before,JSON.stringify(initial));
assert.throws(()=>stock.commitAdd(initial,nasal,{read:()=>before,write:()=>{}}),/verification failed/);
const edited=stock.edit(both.next,{id:'capsules-a',remainingCount:28,transactionId:'adjust-1'});
assert.equal(edited.next.formulationStocks[0].remainingCount,28);
assert.equal(both.next.formulationStocks[0].remainingCount,30,'adjustment immutable');
assert.equal(edited.next.formulationStocks[0].transactions[0].before.remainingCount,30);
assert.equal(edited.next.formulationStocks[0].transactions[0].after.remainingCount,28);
assert.deepEqual(edited.next.supplies,initial.supplies);
assert.throws(()=>stock.edit(edited.next,{id:'capsules-a',remainingCount:27,transactionId:'adjust-1'}),/Duplicate/);
assert.throws(()=>stock.edit(edited.next,{id:'capsules-a',remainingCount:-1,transactionId:'adjust-2'}),/balance/);
const editedNasal=stock.edit(edited.next,{id:'nasal-a',remainingMl:6,remainingMg:8,transactionId:'adjust-3'});
assert.equal(editedNasal.next.formulationStocks[1].transactions.length,1);
assert.throws(()=>stock.edit(editedNasal.next,{id:'nasal-a',remainingMl:4,remainingMg:-2,transactionId:'adjust-4'}),/balance/);
let editStore=JSON.stringify(both.next);
const editAdapter={read:()=>editStore,write:v=>{editStore=v}};
stock.commitEdit(both.next,{id:'capsules-a',remainingCount:29,transactionId:'adjust-durable'},editAdapter);
assert.equal(JSON.parse(editStore).formulationStocks[0].remainingCount,29);
assert.throws(()=>stock.commitEdit(both.next,{id:'capsules-a',remainingCount:28,transactionId:'adjust-stale'},editAdapter),/changed/);
const rawStock=stock.add(initial,{id:'raw-1',compound:'Fictional GHK-Cu',containerType:'raw-powder',method:'Unassigned',quantityMg:500});
const topicalStock=stock.add(rawStock.next,{id:'topical-1',compound:'Fictional GHK-Cu',containerType:'topical-container',method:'Topical',volumeMl:30});
assert.equal(topicalStock.next.formulationStocks[0].remainingMg,500);
assert.equal(topicalStock.next.formulationStocks[1].remainingMl,30);
assert.deepEqual(topicalStock.next.supplies,initial.supplies);
assert.throws(()=>stock.add(initial,{id:'raw-bad',compound:'X',containerType:'raw-powder',method:'Nasal',quantityMg:500}),/mismatch/);
assert.throws(()=>stock.add(initial,{id:'top-bad',compound:'X',containerType:'topical-container',method:'Topical',volumeMl:-2}),/volume/);
const rawAdjust=stock.edit(topicalStock.next,{id:'raw-1',remainingMg:400,transactionId:'raw-adjust-1'});
assert.equal(rawAdjust.next.formulationStocks[0].remainingMg,400);
assert.equal(topicalStock.next.formulationStocks[0].remainingMg,500);
const topAdjust=stock.edit(rawAdjust.next,{id:'topical-1',remainingMl:25,transactionId:'top-adjust-1'});
assert.equal(topAdjust.next.formulationStocks[1].transactions[0].before.remainingMl,30);
console.log('PASS: formulation separation, immutable vials/history, guarded write, stale save, failed save and invalid containers');
