const assert=require('node:assert/strict');
const stock=require('../assets/js/nexus-formulation-stock.js');
const fixture=()=>({supplies:[{id:'vial-existing',name:'Fictional Slew',vials:[{id:'original-vial',remainingMg:10}]}],peptides:{'Fictional Slew':{doses:[{id:'historical',dose:'2',site:'Abdomen — lower L'}]}}});
const oral={id:'capsules-a',compound:'Fictional Slew',containerType:'capsule-bottle',method:'Oral',count:30,mgPerCapsule:5};
const nasal={id:'nasal-a',compound:'Fictional Slew',containerType:'nasal-bottle',method:'Nasal',volumeMl:7,quantityMg:10};
let initial=fixture(),a=stock.add(initial,oral),both=stock.add(a.next,nasal);
assert.deepEqual(initial,fixture(),'original untouched');
assert.deepEqual(both.next.supplies,initial.supplies,'legacy vials unaffected');
assert.deepEqual(both.next.peptides,initial.peptides,'historical dose untouched');
assert.equal(both.next.formulationStocks[0].remainingCount,30);
assert.equal(both.next.formulationStocks[1].remainingMl,7);
assert.equal(both.next.formulationStocks[1].mgPerSpray,null,'no guessed spray strength');
assert.throws(()=>stock.add(both.next,oral),/Duplicate/);
assert.throws(()=>stock.add(initial,{...oral,method:'SubQ'}),/mismatch/);
assert.throws(()=>stock.add(initial,{...oral,count:2.5}),/count/);
assert.throws(()=>stock.add(initial,{...oral,mgPerCapsule:0}),/mg per capsule/);
assert.throws(()=>stock.add(initial,{...nasal,volumeMl:-1}),/volume/);
assert.throws(()=>stock.add(initial,{...nasal,quantityMg:NaN}),/quantity/);
assert.throws(()=>stock.add(initial,{...oral,containerType:'vial'}),/Unsupported/);
let saved=JSON.stringify(initial),writes=0;
const adapter={read:()=>saved,write:v=>{saved=v;writes++}};
const c=stock.commitAdd(initial,oral,adapter);
assert.equal(writes,1);
assert.equal(c.next.formulationStocks.length,1);
assert.equal(JSON.parse(saved).formulationStocks[0].remainingCount,30);
assert.deepEqual(initial,fixture(),'memory remains old until explicit successful swap');
assert.throws(()=>stock.commitAdd(initial,nasal,adapter),/changed/);
assert.equal(writes,1,'stale writes blocked');
let before=JSON.stringify(initial);
assert.throws(()=>stock.commitAdd(initial,nasal,{read:()=>before,write:()=>{throw Error('Quota exceeded')}}),/Quota/);
assert.equal(before,JSON.stringify(initial));
assert.throws(()=>stock.commitAdd(initial,nasal,{read:()=>before,write:()=>{}}),/verification failed/);
console.log('PASS: formulation separation, immutable vials/history, guarded write, stale save, failed save and invalid containers');
